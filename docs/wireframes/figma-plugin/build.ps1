# 와이어프레임 SVG 14개를 내장한 Figma 플러그인 code.js 생성
# SVG를 수정한 뒤 이 스크립트를 다시 실행하면 플러그인이 갱신된다.
$dir = Split-Path $PSScriptRoot -Parent
$out = $PSScriptRoot

$screens = @(
  @{ n = '01 Index';          f = 'index.svg' },
  @{ n = '02 Login';          f = 'login.svg' },
  @{ n = '03 Join';           f = 'join.svg' },
  @{ n = '04 Product Main';   f = 'product-main.svg' },
  @{ n = '05 Product Detail'; f = 'product-detail.svg' },
  @{ n = '06 Product Form';   f = 'product-form.svg' },
  @{ n = '07 Product Edit';   f = 'product-edit.svg' },
  @{ n = '08 Profile';        f = 'profile.svg' },
  @{ n = '09 Profile Edit';   f = 'profile-edit.svg' },
  @{ n = '10 Board List';     f = 'board-list.svg' },
  @{ n = '11 Board View';     f = 'board-view.svg' },
  @{ n = '12 Board Write';    f = 'board-write.svg' },
  @{ n = '13 Cart';           f = 'cart.svg' },
  @{ n = '14 Error';          f = 'error.svg' }
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// auto-generated by build.ps1 — 직접 수정하지 말 것')
[void]$sb.AppendLine('const SCREENS = [')
foreach ($s in $screens) {
  $svg = [IO.File]::ReadAllText((Join-Path $dir $s.f), [Text.Encoding]::UTF8)
  # JS 템플릿 리터럴 이스케이프 (백슬래시, 백틱)
  $esc = $svg.Replace('\', '\\').Replace('`', '\`')
  [void]$sb.AppendLine("  { name: '$($s.n)', svg: ``$esc`` },")
}
[void]$sb.AppendLine('];')
[void]$sb.AppendLine(@'

(async () => {
  const GAP = 80;
  let x = 0;
  const frames = [];
  for (const s of SCREENS) {
    const node = figma.createNodeFromSvg(s.svg);
    node.name = s.name;
    figma.currentPage.appendChild(node);
    node.x = x;
    node.y = 0;
    x += node.width + GAP;
    frames.push(node);
  }
  // 프레임 위에 화면 이름 라벨 (Inter는 Figma 기본 폰트)
  try {
    await figma.loadFontAsync({ family: 'Inter', style: 'Medium' });
    for (const f of frames) {
      const label = figma.createText();
      label.fontName = { family: 'Inter', style: 'Medium' };
      label.fontSize = 16;
      label.characters = f.name;
      label.x = f.x;
      label.y = -40;
      label.fills = [{ type: 'SOLID', color: { r: 0.45, g: 0.45, b: 0.45 } }];
    }
  } catch (e) { /* 라벨 생성 실패해도 프레임은 유지 */ }
  figma.viewport.scrollAndZoomIntoView(frames);
  figma.closePlugin('와이어프레임 14개 화면을 캔버스에 추가했습니다');
})();
'@)

[IO.File]::WriteAllText((Join-Path $out 'code.js'), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "code.js 생성 완료: $((Get-Item (Join-Path $out 'code.js')).Length) bytes"
